/**
 * Static map of a codebase's security gates: the functions whose names say
 * they decide whether something is allowed, ranked by likely security
 * weight, plus "twin" groups of gates that implement the same contract and
 * the guard calls each twin makes. Line-based and regex-only: no parsing, no
 * network, no LLM.
 *
 * Keep in step with python/rafter_cli/scanners/gate_scanner.py. Both runtimes
 * must produce identical output for the same tree (see CLI_SPEC.md).
 */
import fs from "fs";
import path from "path";
