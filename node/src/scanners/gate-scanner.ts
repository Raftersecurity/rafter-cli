/** First words that mark accessors and plumbing, not decisions: never a gate. */
const NON_DECIDING = new Set([
  "get", "set", "load", "list", "delete", "remove", "update", "save", "print", "log", "format",
  "render", "fetch", "write", "read", "to", "from", "parse", "test", "mock", "fake", "default",
  "register", "add", "with", "on", "handle", "init", "reset", "clear", "create", "find",
  "map", "export", "merge", "compute", "resolve", "build", "run", "show", "count",
]);

/** Security tokens in a name: a token matches a word that starts with it. */
const STRONG_NAME_TOKENS: [string, number][] = [
  ["authoriz", 3], ["authoris", 3], ["authent", 3], ["permission", 3], ["privilege", 3],
  ["rbac", 3], ["acl", 3], ["policy", 2], ["csrf", 3], ["xsrf", 3], ["admin", 2], ["owner", 2],
  ["role", 1], ["scope", 1], ["access", 2], ["token", 2], ["jwt", 2], ["session", 2],
  ["signature", 2], ["hmac", 2], ["cert", 2], ["tls", 2], ["oauth", 2], ["saml", 2],
  ["oidc", 2], ["password", 2], ["credential", 2], ["login", 2], ["origin", 2],
  ["redirect", 2], ["host", 1], ["domain", 1], ["url", 1], ["path", 1], ["cors", 2],
  ["trusted", 2], ["mfa", 2], ["otp", 2], ["nonce", 2], ["secret", 2], ["key", 1],
];

/** Security-ish path words (directory or file stem); one +2 per path. */
const PATH_TOKENS = [
  "auth", "authz", "authn", "acl", "policy", "policies", "permission", "session", "token",
  "oauth", "oidc", "saml", "jwt", "crypto", "tls", "cert", "middleware", "guard", "security",
  "access", "login", "rbac", "iam", "sso", "csrf", "sanitiz", "escape", "secure",
];

function isAuthorWord(w: string): boolean {
  return w.startsWith("author") && !w.startsWith("authoriz") && !w.startsWith("authoris");
}

function nameWeight(words: string[], kind: Gate["kind"]): number {
  if (words.length === 0) return 0;
  let first = words[0];
  if (NON_DECIDING.has(first)) return 0;
  // aauthenticate, acheck_password: the a-prefixed async variant of a verb.
  if (!VERBS.has(first) && first.length > 3 && first.startsWith("a") && VERBS.has(first.slice(1))) first = first.slice(1);
  let verb = 0;
  if (kind !== "type") {
    if (VERBS.has(first)) verb = VERBS.get(first)!;
    else if (first === "is" && words.slice(1).some((w) => IS_WORDS.has(w))) verb = 2;
    else if (first === "has" && words.slice(1).some((w) => HAS_WORDS.has(w))) verb = 3;
    else if (words.length > 1 && (words[words.length - 1] === "match" || words[words.length - 1] === "matches" || words[words.length - 1] === "matcher")) verb = 1;
  }
  let role = 0;
  for (const w of words) {
    const r = ROLE_WORDS.get(w) ?? 0;
    if (r > role) role = r;
  }
  if (kind === "type" && role < 2) return 0; // a type is a gate only by its role word
  return Math.max(verb, role);
}

function tokenWeight(words: string[]): number {
  const ws = words.filter((w) => !isAuthorWord(w));
  let total = 0;
  for (const [tok, w] of STRONG_NAME_TOKENS) {
    if (ws.some((x) => x.startsWith(tok))) total += w;
  }
  return Math.min(total, 6);
}

function pathWeight(rel: string): number {
  const segs = rel.split("/");
  segs[segs.length - 1] = segs[segs.length - 1].replace(/\.[^.]*$/, "");
  for (const seg of segs) {
    for (const w of splitWords(seg)) {
      if (isAuthorWord(w)) continue;
      if (PATH_TOKENS.some((t) => w.startsWith(t))) return 2;
    }
  }
  return 0;
}

