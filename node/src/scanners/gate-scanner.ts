const MAX_SIGNATURE = 90;
// Longer lines are minified or data, not definitions; skipping them also
// bounds regex backtracking.
const MAX_DEF_LINE = 400;

function scanFile(abs: string, rel: string, lang: string, out: GateInternal[], leads: LeadState): boolean {
  let content: string;
  try {
    const st = fs.statSync(abs);
    if (st.size > MAX_FILE_BYTES) return false;
    content = fs.readFileSync(abs, "utf-8");
  } catch {
    return false;
  }
  const raw = content.split("\n").map((l) => (l.endsWith("\r") ? l.slice(0, -1) : l));
  if (GENERATED_MARK_RE.test(raw.slice(0, 5).join("\n"))) return false;
  // Go test support outside _test.go files (a harness package) imports "testing".
  if (lang === "go" && raw.slice(0, 80).some((l) => GO_TESTING_IMPORT.test(l))) return false;
  // Python: code inside docstrings is an example, not a definition.
  const lines = lang === "python" ? blankTripleQuoted(raw) : raw;
  const pw = pathWeight(rel);
  scanLeads(leads, rel, lang, raw, pw);
  for (let i = 0; i < lines.length; i++) {
    if (lines[i].length > MAX_DEF_LINE) continue;
    const def = matchDef(lang, lines[i]);
    if (!def) continue;
    const words = splitWords(def.name);
    const nw = nameWeight(words, def.kind);
    if (nw === 0) continue;
    let sig = raw[i].trim();
    if (sig.length > MAX_SIGNATURE) sig = sig.slice(0, MAX_SIGNATURE - 3) + "...";
    const calls = new Set<string>();
    let guards: Record<string, string[]> = {};
    let stub = false;
    if (def.kind !== "type") {
      const code = bodyCode(bodyLines(lang, lines, i), lang);
      guards = guardCalls(code, def.name, calls);
      stub = isStub(code);
    }
    out.push({
      file: rel,
      line: i + 1,
      name: def.name,
      kind: def.kind,
      language: lang,
      score: nw + tokenWeight(words) + pw,
      signature: sig,
      guards,
      calls,
      stub,
    });
  }
  return true;
}

/** Map the security gates under `target` (a directory or a single file). */
export function mapGates(target: string, opts: { limit: number; respectGitignore?: boolean }): GateMap {
  const root = path.resolve(target);
  const st = fs.statSync(root);
  let files: string[];
  let base: string;
  if (st.isDirectory()) {
    files = [];
    walk(root, 0, files);
    if (opts.respectGitignore !== false) files = filterGitIgnored(files, root);
    base = root;
  } else {
    files = LANG_BY_EXT[path.extname(root)] ? [root] : [];
    base = path.dirname(root);
  }
  const gates: GateInternal[] = [];
  const leadState = newLeadState();
  let scanned = 0;
  for (const abs of files) {
    const rel = path.relative(base, abs).split(path.sep).join("/");
    if (scanFile(abs, rel, LANG_BY_EXT[path.extname(abs)], gates, leadState)) scanned++;
  }
  gates.sort((a, b) => b.score - a.score || cmp(a.file, b.file) || a.line - b.line);
  const twins = buildTwins(gates);
  const leads = finishLeads(leadState);
  const shown = gates.slice(0, opts.limit).map(({ guards, calls, stub, ...g }) => g);
  return {
    stats: {
      files_scanned: scanned,
      gates_found: gates.length,
      gates_shown: shown.length,
      twin_groups: twins.length,
      flagged_groups: twins.filter((t) => t.flagged).length,
      leads_found: leads.found,
    },
    gates: shown,
    leads: leads.leads,
    twins,
  };
}

// ── Text ─────────────────────────────────────────────────────────────

const MAX_FLAGGED_TEXT = 10;
const MAX_MEMBERS_TEXT = 5;
const MAX_OTHER_TEXT = 8;
const MAX_LEADS_TEXT = 25;

function guardSummary(guards: Record<string, string[]>): string {
  const parts = Object.entries(guards).map(([c, ids]) => `${c}: ${ids.slice(0, 2).join(", ")}`);
  return parts.length ? parts.join("; ") : "no guard calls";
}

export function formatGateMap(map: GateMap): string {
  const s = map.stats;
  const out: string[] = [];
  out.push(`rafter gates: ${s.files_scanned} files scanned, ${s.gates_found} gates found, ${s.twin_groups} twin groups, ${s.flagged_groups} flagged`);
  out.push("");
  out.push(`Gates (top ${s.gates_shown} of ${s.gates_found}, ranked by likely security weight; score file:line signature):`);
  for (const g of map.gates) out.push(`  ${g.score}  ${g.file}:${g.line}  ${g.signature}`);
  if (s.gates_shown < s.gates_found) out.push(`  ... ${s.gates_found - s.gates_shown} more (--limit N or --json)`);

  const leadsShown = map.leads.slice(0, MAX_LEADS_TEXT);
  out.push("");
  out.push(`Leads (top ${leadsShown.length} of ${s.leads_found}; places to look deeper, each a question to answer by reading the code, not a finding):`);
  if (leadsShown.length === 0) out.push("  none");
  for (const l of leadsShown) out.push(`  ${l.file}:${l.line}  [${l.rule}]  ${l.question}`);
  if (s.leads_found > leadsShown.length) out.push(`  ... ${s.leads_found - leadsShown.length} more, use --json`);

  const flagged = map.twins.filter((t) => t.flagged);
  const other = map.twins.filter((t) => !t.flagged);
  out.push("");
  out.push("Flagged twin groups (same contract; a member lacks a guard its twins call; highest confidence first):");
  if (flagged.length === 0) out.push("  none");
  for (const t of flagged.slice(0, MAX_FLAGGED_TEXT)) {
    out.push(`  ${t.key} (${t.members.length}): missing ${t.missing.join(", ")}; confidence ${t.confidence}`);
    for (const m of t.members.slice(0, MAX_MEMBERS_TEXT)) {
      let tail = "";
      if (m.status !== "checked") tail = m.status === "stub" ? "  (stub)" : "  (delegates to a twin)";
      else if (m.lacks.length) {
        const ids = m.lacks_calls.slice(0, 3).map((id) => `${id}()`).join(", ");
        const more = m.lacks_calls.length > 3 ? ` +${m.lacks_calls.length - 3}` : "";
        tail = `  lacks: ${m.lacks.join(", ")} (twins call ${ids}${more}; this one does not)`;
      }
      out.push(`    ${m.file}:${m.line}  ${m.name}  [${guardSummary(m.guards)}]${tail}`);
    }
    if (t.members.length > MAX_MEMBERS_TEXT) out.push(`    ... ${t.members.length - MAX_MEMBERS_TEXT} more members (--json)`);
  }
  if (flagged.length > MAX_FLAGGED_TEXT) out.push(`  ... ${flagged.length - MAX_FLAGGED_TEXT} more flagged groups (--json)`);

  out.push("");
  out.push("Other twin groups:");
  if (other.length === 0) out.push("  none");
  for (const t of other.slice(0, MAX_OTHER_TEXT)) {
    const ms = t.members.slice(0, 4).map((m) => `${m.file}:${m.line}`).join(", ");
    const more = t.members.length > 4 ? `, +${t.members.length - 4}` : "";
    out.push(`  ${t.key} (${t.members.length}): ${ms}${more}`);
  }
  if (other.length > MAX_OTHER_TEXT) out.push(`  ... ${other.length - MAX_OTHER_TEXT} more (--json)`);
  out.push("");
  out.push("Next: read each gate, state its contract, and name an input it should reject but accepts; answer each lead you reach (rafter-code-review, section 0).");
  return out.join("\n") + "\n";
}
