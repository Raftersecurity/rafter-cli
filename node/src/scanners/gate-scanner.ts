const GO_FUNC = /^[ \t\n\r\f\v]*func[ \t\n\r\f\v]+(\([^)]*\)[ \t\n\r\f\v]*)?([A-Za-z_]\w*)[ \t\n\r\f\v]*(\[[^\]]*\][ \t\n\r\f\v]*)?\(/;
const GO_TYPE = /^[ \t\n\r\f\v]*type[ \t\n\r\f\v]+([A-Za-z_]\w*)[ \t\n\r\f\v]+(struct|interface|func)\b/;
const PY_DEF = /^([ \t\n\r\f\v]*)(async[ \t\n\r\f\v]+)?def[ \t\n\r\f\v]+([A-Za-z_]\w*)[ \t\n\r\f\v]*\(/;
const PY_CLASS = /^[ \t\n\r\f\v]*class[ \t\n\r\f\v]+([A-Za-z_]\w*)/;
const JS_FUNC = /^[ \t\n\r\f\v]*(export[ \t\n\r\f\v]+)?(default[ \t\n\r\f\v]+)?(async[ \t\n\r\f\v]+)?function[ \t\n\r\f\v]*\*?[ \t\n\r\f\v]*([A-Za-z_$][\w$]*)[ \t\n\r\f\v]*[<(]/;
const JS_VAR = /^[ \t\n\r\f\v]*(export[ \t\n\r\f\v]+)?(const|let|var)[ \t\n\r\f\v]+([A-Za-z_$][\w$]*)[ \t\n\r\f\v]*(:[^=]+)?=[ \t\n\r\f\v]*(async[ \t\n\r\f\v]+)?(function\b|[A-Za-z_$][\w$]*[ \t\n\r\f\v]*=>|\()/;
const JS_PROP = /^[ \t\n\r\f\v]*([A-Za-z_$][\w$]*)[ \t\n\r\f\v]*:[ \t\n\r\f\v]*(async[ \t\n\r\f\v]+)?(function\b|[A-Za-z_$][\w$]*[ \t\n\r\f\v]*=>|\()/;
const JS_EXPORTS = /^[ \t\n\r\f\v]*(module\.)?exports\.([A-Za-z_$][\w$]*)[ \t\n\r\f\v]*=[ \t\n\r\f\v]*(async[ \t\n\r\f\v]+)?(function\b|[A-Za-z_$][\w$]*[ \t\n\r\f\v]*=>|\()/;
const JS_PROTO = /^[ \t\n\r\f\v]*[\w$.]+\.prototype\.([A-Za-z_$][\w$]*)[ \t\n\r\f\v]*=[ \t\n\r\f\v]*(async[ \t\n\r\f\v]+)?function\b/;
const JS_METHOD = /^[ \t\n\r\f\v]+((public|private|protected|static|async|override|readonly)[ \t\n\r\f\v]+)*([A-Za-z_$][\w$]*)[ \t\n\r\f\v]*(<[^>]*>)?[ \t\n\r\f\v]*\([^\n]*\)[ \t\n\r\f\v]*(:[ \t\n\r\f\v]*[^{;=]+)?\{[ \t\n\r\f\v]*$/;
const JS_CLASS = /^[ \t\n\r\f\v]*(export[ \t\n\r\f\v]+)?(default[ \t\n\r\f\v]+)?(abstract[ \t\n\r\f\v]+)?class[ \t\n\r\f\v]+([A-Za-z_$][\w$]*)/;
const JAVA_METHOD = /^[ \t\n\r\f\v]*(@\w+[ \t\n\r\f\v]+)*((public|private|protected|static|final|synchronized|abstract|default|native)[ \t\n\r\f\v]+)*(<[^>]+>[ \t\n\r\f\v]+)?[\w$.<>\[\],? ]*?[\w$>\]][ \t\n\r\f\v]+([a-z_$][\w$]*)[ \t\n\r\f\v]*\(/;
const JAVA_CLASS = /^[ \t\n\r\f\v]*((public|private|protected|static|final|abstract)[ \t\n\r\f\v]+)*(class|interface|enum|record)[ \t\n\r\f\v]+([A-Za-z_$][\w$]*)/;
const RB_DEF = /^[ \t\n\r\f\v]*def[ \t\n\r\f\v]+(self\.)?([A-Za-z_]\w*[?!]?)/;
const RB_CLASS = /^[ \t\n\r\f\v]*class[ \t\n\r\f\v]+([A-Z]\w*)/;

const KEYWORDS = new Set([
  "if", "for", "while", "switch", "catch", "function", "return", "else", "do", "try", "with",
  "new", "throw", "case", "typeof", "await", "yield", "delete", "void", "super", "this",
  "elif", "except", "lambda", "not", "and", "or", "in", "is", "assert", "print", "def",
  "class", "import", "from", "raise", "pass", "select", "go", "defer", "range", "func",
  "make", "len", "cap", "append", "panic", "recover", "sizeof", "constructor",
]);

function matchDef(lang: string, line: string): Def | null {
  let m: RegExpMatchArray | null;
  switch (lang) {
    case "go":
      if ((m = line.match(GO_FUNC))) return { name: m[2], kind: m[1] ? "method" : "function" };
      if ((m = line.match(GO_TYPE))) return { name: m[1], kind: "type" };
      return null;
    case "python":
      if ((m = line.match(PY_DEF))) return { name: m[3], kind: m[1].length > 0 ? "method" : "function" };
      if ((m = line.match(PY_CLASS))) return { name: m[1], kind: "type" };
      return null;
    case "javascript":
    case "typescript": {
      const t = trimEndA(line);
      if ((m = line.match(JS_FUNC))) return t.endsWith(";") ? null : { name: m[4], kind: "function" };
      if ((m = line.match(JS_VAR))) return arrowOk(m[6], t) ? { name: m[3], kind: "function" } : null;
      if ((m = line.match(JS_EXPORTS))) return arrowOk(m[4], t) ? { name: m[2], kind: "function" } : null;
      if ((m = line.match(JS_PROTO))) return { name: m[1], kind: "method" };
      if ((m = line.match(JS_CLASS))) return { name: m[4], kind: "type" };
      if ((m = line.match(JS_PROP))) return arrowOk(m[3], t) ? { name: m[1], kind: "method" } : null;
      if ((m = line.match(JS_METHOD))) return KEYWORDS.has(m[3]) ? null : { name: m[3], kind: "method" };
      return null;
    }
    case "java": {
      if ((m = line.match(JAVA_CLASS))) return { name: m[4], kind: "type" };
      const t = trimEndA(line);
      if (t.endsWith(";")) return null;
      if ((m = line.match(JAVA_METHOD))) {
        const firstWord = trimA(line).split(/[ \t\n\r\f\v(]/)[0];
        if (KEYWORDS.has(firstWord) || KEYWORDS.has(m[5])) return null;
        return { name: m[5], kind: "method" };
      }
      return null;
    }
    case "ruby":
      if ((m = line.match(RB_DEF))) return { name: m[2].replace(/[?!]$/, ""), kind: m[1] ? "function" : "method" };
      if ((m = line.match(RB_CLASS))) return { name: m[1], kind: "type" };
      return null;
  }
  return null;
}

/** A `(` after `=` is a function only if an arrow follows on the line or the params continue. */
function arrowOk(head: string, line: string): boolean {
  if (head !== "(") return true;
  return line.includes("=>") || line.endsWith("(") || line.endsWith(",");
}

// ── Bodies and guard calls ───────────────────────────────────────────

const MAX_BODY_LINES = 400;

function indentOf(line: string): number {
  return line.length - trimStartA(line).length;
}

/**
 * Remove string literals and line comments so braces inside them don't count.
 * Each closed literal becomes `""`; an unclosed quote is kept and the scan
 * goes on after it. One linear pass: a regex for this backtracks
 * quadratically on a long line with an unclosed quote. Once a quote is
 * unclosed, every later quote of that kind is too (its scan would fall into
 * step with the first one), so each kind is scanned to the end at most once.
 */
function stripCode(line: string, hashComments = false): string {
  let out = "";
  let unclosed = "";
  let i = 0;
  while (i < line.length) {
    const ch = line[i];
    if ((ch === '"' || ch === "'" || ch === "`") && !unclosed.includes(ch)) {
      let j = i + 1;
      while (j < line.length && line[j] !== ch) j += line[j] === "\\" ? 2 : 1;
      if (j < line.length) {
        out += '""';
        i = j + 1;
        continue;
      }
      unclosed += ch;
    } else if ((ch === "/" && line[i + 1] === "/") || (hashComments && ch === "#")) {
      break;
    }
    out += ch;
    i++;
  }
  return out;
}

/** Indexes of the lines in the body of the definition at `start`. */
function bodyLines(lang: string, lines: string[], code: string[], start: number): number[] {
  const end = Math.min(lines.length, start + MAX_BODY_LINES);
  if (lang === "python" || lang === "ruby") {
    const base = indentOf(lines[start]);
    const body = [start];
    for (let i = start + 1; i < end; i++) {
      const l = lines[i];
      if (trimA(l) === "") continue;
      if (indentOf(l) <= base) {
        if (lang === "ruby" && trimA(l).startsWith("end")) break;
        if (lang === "python" && /^[ \t\n\r\f\v]*[)\]]/.test(l)) { body.push(i); continue; }
        break;
      }
      body.push(i);
    }
    return body;
  }
  // Brace languages.
  let depth = 0;
  let opened = false;
  const body: number[] = [];
  for (let i = start; i < end; i++) {
    body.push(i);
    for (const ch of code[i]) {
      if (ch === "{") { depth++; opened = true; }
      else if (ch === "}") depth--;
    }
    if (opened && depth <= 0) break;
    if (!opened && i - start >= 3) break;
    if (!opened && trimEndA(code[i]).endsWith(";")) break;
  }
  return body;
}

// The lookbehind starts a match only at the head of an identifier, so a long
// run of identifier characters is scanned once instead of once per character.
const CALL_RE = /(?<![\w$])([A-Za-z_$][\w$]*)[ \t\n\r\f\v]*\(/g;

/**
 * Guard categories, matched against the called name lowercased with
 * underscores removed, with the
 * weight a missing one carries when ranking twin groups. Order is output order.
 */
const GUARD_CATEGORIES: [string, RegExp, number][] = [
  ["escape", /escape|quote|sanitiz|sanitis|purify|striptags|encodeuri|htmlspecialchars/, 3],
  ["normalize", /clean|normaliz|normalis|normpath|realpath|abspath|evalsymlinks|canonical/, 3],
  ["containment", /^(rel|relpath|relative)$|hasprefix|startswith|hassuffix|endswith|islink|lstat|within|containspath|isrelativeto/, 3],
  ["constant_time", /constanttimecompare|comparedigest|timingsafeequal|securecompare|constanttimeeq|safeequal|^equal$/, 3],
  ["expiry", /expir|revok|notbefore|notafter/, 3],
  ["authz", /authoriz|authoris|permi|allow|deny|forbid|access/, 2],
  ["authn", /authent|login|password/, 2],
  ["limit", /limit|max|bound|truncat|throttle/, 2],
  ["verify", /verif/, 1],
  ["validate", /valid/, 1],
  ["check", /check/, 1],
];
const CATEGORY_WEIGHT = new Map(GUARD_CATEGORIES.map(([c, , w]) => [c, w]));

/** Calls ending in these words construct a value; they are not guards. */
const VALUE_WORDS = new Set(["result", "results", "error", "errors", "exception", "options", "config", "info", "type"]);

const CALL_KEYWORDS = new Set([...KEYWORDS, "require", "import"]);

function guardCalls(code: string[], body: number[], selfName: string): Record<string, string[]> {
  const found: Record<string, Set<string>> = {};
  // Drop the definition's own name from its first line.
  const text = body.map((li, i) => (i === 0 ? code[li].replace(selfName, "") : code[li])).join("\n");
  CALL_RE.lastIndex = 0;
  let m: RegExpExecArray | null;
  while ((m = CALL_RE.exec(text)) !== null) {
    const id = m[1];
    const low = id.toLowerCase().replace(/_/g, "");
    if (low === selfName.toLowerCase().replace(/_/g, "") || CALL_KEYWORDS.has(id)) continue;
    if (low.startsWith("un")) continue; // unquote, unescape: the reverse of a guard
    const idWords = splitWords(id);
    if (idWords.length && VALUE_WORDS.has(idWords[idWords.length - 1])) continue;
    for (const [cat, re] of GUARD_CATEGORIES) {
      if (cat === "constant_time" && low === "equal") {
        const before = text.slice(Math.max(0, m.index - 8), m.index);
        if (!/(hmac|subtle)\.$/.test(before)) continue;
      }
      if (re.test(low)) {
        (found[cat] ??= new Set()).add(id);
        break;
      }
    }
  }
  const out: Record<string, string[]> = {};
  for (const [cat] of GUARD_CATEGORIES) {
    if (found[cat]) out[cat] = [...found[cat]].sort();
  }
  return out;
}

// ── Twins ────────────────────────────────────────────────────────────

/** Variant markers: async/sync pairs, implementations, versions. Dropped anywhere. */
const VARIANT_WORDS = new Set(["async", "sync", "impl", "internal", "inner", "v"]);

/** Backend-ish words: dropped anywhere when what remains still names a contract. */
const BACKEND_WORDS = new Set([
  "legacy", "old", "new", "default", "sql", "sqlite", "postgres", "pg", "mysql", "mongo",
  "redis", "ldap", "local", "memory", "mem", "db", "file", "fs", "http", "grpc", "rest", "ws",
  "s3", "gcs", "azure", "remote",
]);

const SECURITY_WORDS = new Set([
  ...VERBS.keys(), ...IS_WORDS, ...HAS_WORDS, ...ROLE_WORDS.keys(), "is", "has",
]);

/**
 * The contract a gate implements, from its name: `ldapAuthenticate` in
 * ldap.go, `authenticate_async` and `AuthenticateV2` all key to
 * "authenticate". Words naming the file or its directory are dropped from
 * either end of the name. A key reduced to one weak verb ("check") is too
 * generic to pair on, so the unstripped name is used instead.
 */
function twinKey(name: string, rel: string): string {
  let base = splitWords(name).filter((w) => !/^\d+$/.test(w) && !VARIANT_WORDS.has(w));
  if (base.length > 1 && base[0] === "do") base = base.slice(1);
  if (base.length === 0) return "";
  const ctx = new Set<string>();
  const segs = rel.split("/");
  for (const w of splitWords(segs[segs.length - 1].replace(/\.[^.]*$/, ""))) ctx.add(w);
  if (segs.length > 1) for (const w of splitWords(segs[segs.length - 2])) ctx.add(w);
  const strippable = (w: string) => ctx.has(w) && !SECURITY_WORDS.has(w);
  let kept = base.filter((w) => !BACKEND_WORDS.has(w));
  if (kept.length > 1 && strippable(kept[0])) kept = kept.slice(1);
  if (kept.length > 1 && strippable(kept[kept.length - 1])) kept = kept.slice(0, -1);
  const strongBare = kept.length === 1 && (VERBS.get(kept[0]) ?? 0) >= 3;
  if (kept.length === 0 || (kept.length === 1 && !strongBare && base.length > 1)) kept = base;
  return kept.join("");
}

const MAX_TWIN_GROUP = 8;

function buildTwins(gates: GateInternal[]): TwinGroup[] {
  const candidates = gates.filter((g) => g.kind !== "type");
  const keys = candidates.map((g) => twinKey(g.name, g.file));
  const keySet = new Set(keys);
  const groups = new Map<string, GateInternal[]>();
  candidates.forEach((g, i) => {
    let k = keys[i];
    // aauthenticate / acheck_password: an a-prefixed async twin.
    if (k.length > 2 && k.startsWith("a") && keySet.has(k.slice(1))) k = k.slice(1);
    // A bare weak verb (`Check`, `Validate` on unrelated types) names no shared contract.
    if (!k || (VERBS.get(k) ?? 2) < 2) return;
    const list = groups.get(k);
    if (list) list.push(g);
    else groups.set(k, [g]);
  });
  const scored: { t: TwinGroup; sev: number; w: number }[] = [];
  for (const [key, members] of groups) {
    if (members.length < 2 || members.length > MAX_TWIN_GROUP) continue;
    const present = new Set<string>();
    for (const m of members) for (const c of Object.keys(m.guards)) present.add(c);
    const cats = GUARD_CATEGORIES.map(([c]) => c).filter((c) => present.has(c));
    const missing = cats.filter((c) => members.some((m) => !m.guards[c]));
    const t: TwinGroup = {
      key,
      flagged: missing.length > 0,
      missing,
      members: members.map((m) => ({
        file: m.file,
        line: m.line,
        name: m.name,
        guards: m.guards,
        lacks: missing.filter((c) => !m.guards[c]),
      })),
    };
    const severity = Math.max(0, ...missing.map((c) => CATEGORY_WEIGHT.get(c)!));
    scored.push({ t, sev: severity, w: Math.max(...members.map((m) => m.score)) });
  }
  scored.sort((a, b) =>
    b.sev - a.sev ||
    b.w - a.w ||
    b.t.missing.length - a.t.missing.length ||
    cmp(a.t.key, b.t.key));
  return scored.map((s) => s.t);
}

// ── Entry point ──────────────────────────────────────────────────────

const MAX_SIGNATURE = 90;
// Longer lines are minified or data, not definitions; skipping them also
// bounds regex backtracking.
const MAX_DEF_LINE = 400;
// Body lines read per file, summed over its gates. Real files stay far below;
// a file of thousands of unclosed definitions is data, and is skipped like an
// oversize file rather than read 400 lines per definition.
const MAX_BODY_WORK = 100_000;

function scanFile(abs: string, rel: string, lang: string, out: GateInternal[]): boolean {
  let content: string;
  try {
    const st = fs.statSync(abs);
    if (st.size > MAX_FILE_BYTES) return false;
    content = fs.readFileSync(abs, "utf-8");
  } catch {
    return false;
  }
  if (content.startsWith("\uFEFF")) content = content.slice(1);
  const lines = content.split("\n").map((l) => (l.endsWith("\r") ? l.slice(0, -1) : l));
  if (GENERATED_MARK_RE.test(lines.slice(0, 5).join("\n"))) return false;
  // Each line stripped once; bodies overlap, so per-gate stripping is quadratic.
  const code = lines.map((l) => stripCode(l, lang === "python" || lang === "ruby"));
  const pw = pathWeight(rel);
  let bodyWork = 0;
  const found: GateInternal[] = [];
  for (let i = 0; i < lines.length; i++) {
    if (cpLength(lines[i]) > MAX_DEF_LINE) continue;
    const def = matchDef(lang, lines[i]);
    if (!def) continue;
    const words = splitWords(def.name);
    const nw = nameWeight(words, def.kind);
    if (nw === 0) continue;
    let guards: Record<string, string[]> = {};
    if (def.kind !== "type") {
      const body = bodyLines(lang, lines, code, i);
      bodyWork += body.length;
      if (bodyWork > MAX_BODY_WORK) return false;
      guards = guardCalls(code, body, def.name);
    }
    let sig = trimA(lines[i]);
    if (cpLength(sig) > MAX_SIGNATURE) sig = cpSlice(sig, MAX_SIGNATURE - 3) + "...";
    found.push({
      file: rel,
      line: i + 1,
      name: def.name,
      kind: def.kind,
      language: lang,
      score: nw + tokenWeight(words) + pw,
      signature: sig,
      guards,
    });
  }
  for (const g of found) out.push(g);
  return true;
}

/** Map the security gates under `target` (a directory or a single file). */
export function mapGates(target: string, opts: { limit: number; respectGitignore?: boolean }): GateMap {
  const root = path.resolve(target);
  const st = fs.statSync(root);
  let files: string[];
  let base: string;
  if (st.isDirectory()) {
    files = [];
    walk(root, 0, files);
    if (opts.respectGitignore !== false) files = filterGitIgnored(files, root);
    base = root;
  } else {
    files = LANG_BY_EXT[path.extname(root)] ? [root] : [];
    base = path.dirname(root);
  }
  const gates: GateInternal[] = [];
  let scanned = 0;
  for (const abs of files) {
    const rel = path.relative(base, abs).split(path.sep).join("/");
    if (scanFile(abs, rel, LANG_BY_EXT[path.extname(abs)], gates)) scanned++;
  }
  gates.sort((a, b) => b.score - a.score || cmp(a.file, b.file) || a.line - b.line);
  const twins = buildTwins(gates);
  const shown = gates.slice(0, opts.limit).map(({ guards, ...g }) => g);
  return {
    stats: {
      files_scanned: scanned,
      gates_found: gates.length,
      gates_shown: shown.length,
      twin_groups: twins.length,
      flagged_groups: twins.filter((t) => t.flagged).length,
    },
    gates: shown,
    twins,
  };
}

// ── Text ─────────────────────────────────────────────────────────────

const MAX_FLAGGED_TEXT = 10;
const MAX_MEMBERS_TEXT = 5;
const MAX_OTHER_TEXT = 8;

function guardSummary(guards: Record<string, string[]>): string {
  const parts = Object.entries(guards).map(([c, ids]) => `${c}: ${ids.slice(0, 2).join(", ")}`);
  return parts.length ? parts.join("; ") : "no guard calls";
}

export function formatGateMap(map: GateMap): string {
  const s = map.stats;
  const out: string[] = [];
  out.push(`rafter gates: ${s.files_scanned} files scanned, ${s.gates_found} gates found, ${s.twin_groups} twin groups, ${s.flagged_groups} flagged`);
  out.push("");
  out.push(`Gates (top ${s.gates_shown} of ${s.gates_found}, ranked by likely security weight; score file:line signature):`);
  for (const g of map.gates) out.push(`  ${g.score}  ${g.file}:${g.line}  ${g.signature}`);
  if (s.gates_shown < s.gates_found) out.push(`  ... ${s.gates_found - s.gates_shown} more (--limit N or --json)`);

  const flagged = map.twins.filter((t) => t.flagged);
  const other = map.twins.filter((t) => !t.flagged);
  out.push("");
  out.push("Flagged twin groups (same contract; a member lacks a guard its twins call):");
  if (flagged.length === 0) out.push("  none");
  for (const t of flagged.slice(0, MAX_FLAGGED_TEXT)) {
    out.push(`  ${t.key} (${t.members.length}): missing ${t.missing.join(", ")}`);
    for (const m of t.members.slice(0, MAX_MEMBERS_TEXT)) {
      const lacks = m.lacks.length ? `  lacks: ${m.lacks.join(", ")}` : "";
      out.push(`    ${m.file}:${m.line}  ${m.name}  [${guardSummary(m.guards)}]${lacks}`);
    }
    if (t.members.length > MAX_MEMBERS_TEXT) out.push(`    ... ${t.members.length - MAX_MEMBERS_TEXT} more members (--json)`);
  }
  if (flagged.length > MAX_FLAGGED_TEXT) out.push(`  ... ${flagged.length - MAX_FLAGGED_TEXT} more flagged groups (--json)`);

  out.push("");
  out.push("Other twin groups:");
  if (other.length === 0) out.push("  none");
  for (const t of other.slice(0, MAX_OTHER_TEXT)) {
    const ms = t.members.slice(0, 4).map((m) => `${m.file}:${m.line}`).join(", ");
    const more = t.members.length > 4 ? `, +${t.members.length - 4}` : "";
    out.push(`  ${t.key} (${t.members.length}): ${ms}${more}`);
  }
  if (other.length > MAX_OTHER_TEXT) out.push(`  ... ${other.length - MAX_OTHER_TEXT} more (--json)`);
  out.push("");
  out.push("Next: read each gate, state its contract, and name an input it should reject but accepts (rafter-code-review, section 0).");
  return out.join("\n") + "\n";
}
