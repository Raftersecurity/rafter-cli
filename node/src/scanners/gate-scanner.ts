export interface Gate {
  file: string;
  line: number;
  name: string;
  kind: "function" | "method" | "type";
  language: string;
  score: number;
  signature: string;
}

export interface TwinMember {
  file: string;
  line: number;
  name: string;
  /** `checked`; `delegates` when it calls a twin or `super`; `stub` when its body is empty or only raises. */
  status: "checked" | "delegates" | "stub";
  guards: Record<string, string[]>;
  lacks: string[];
  /** The guard calls its twins make in the categories it lacks. */
  lacks_calls: string[];
}

export interface TwinGroup {
  key: string;
  flagged: boolean;
  confidence: number;
  missing: string[];
  members: TwinMember[];
}

export interface GateMap {
  stats: {
    files_scanned: number;
    gates_found: number;
    gates_shown: number;
    twin_groups: number;
    flagged_groups: number;
    leads_found: number;
  };
  gates: Gate[];
  leads: Lead[];
  twins: TwinGroup[];
}

interface GateInternal extends Gate {
  guards: Record<string, string[]>;
  calls: Set<string>;
  stub: boolean;
}

