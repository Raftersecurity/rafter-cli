_TOKEN_WEIGHT = dict(STRONG_NAME_TOKENS)
_MIN_TOKEN = min(len(t) for t in _TOKEN_WEIGHT)
_MAX_TOKEN = max(len(t) for t in _TOKEN_WEIGHT)

# Security-ish path words (directory or file stem); one +2 per path.
PATH_TOKENS = [
    "auth", "authz", "authn", "acl", "policy", "policies", "permission", "session", "token",
    "oauth", "oidc", "saml", "jwt", "crypto", "tls", "cert", "middleware", "guard", "security",
    "access", "login", "rbac", "iam", "sso", "csrf", "sanitiz", "escape", "secure",
]


_PATH_TOKEN_SET = set(PATH_TOKENS)
_MIN_PATH_TOKEN = min(len(t) for t in PATH_TOKENS)
_MAX_PATH_TOKEN = max(len(t) for t in PATH_TOKENS)


def _is_author_word(w: str) -> bool:
    return w.startswith("author") and not w.startswith("authoriz") and not w.startswith("authoris")


def _name_weight(words: list[str], kind: str) -> int:
    if not words:
        return 0
    first = words[0]
    if first in NON_DECIDING:
        return 0
    # aauthenticate, acheck_password: the a-prefixed async variant of a verb.
    if first not in VERBS and len(first) > 3 and first.startswith("a") and first[1:] in VERBS:
        first = first[1:]
    verb = 0
    if kind != "type":
        if first in VERBS:
            verb = VERBS[first]
        elif first == "is" and any(w in IS_WORDS for w in words[1:]):
            verb = 2
        elif first == "has" and any(w in HAS_WORDS for w in words[1:]):
            verb = 3
        elif len(words) > 1 and words[-1] in ("match", "matches", "matcher"):
            verb = 1
    role = max([ROLE_WORDS.get(w, 0) for w in words] + [0])
    if kind == "type" and role < 2:
        return 0  # a type is a gate only by its role word
    return max(verb, role)


def _token_weight(words: list[str]) -> int:
    matched: set[str] = set()
    for w in words:
        if _is_author_word(w):
            continue
        for n in range(_MIN_TOKEN, min(len(w), _MAX_TOKEN) + 1):
            if w[:n] in _TOKEN_WEIGHT:
                matched.add(w[:n])
    return min(sum(_TOKEN_WEIGHT[t] for t in matched), 6)


_EXT_RE = re.compile(r"\.[^.]*$", A)


def _path_weight(rel: str) -> int:
    segs = rel.split("/")
    segs[-1] = _EXT_RE.sub("", segs[-1], count=1)
    for seg in segs:
        for w in split_words(seg):
            if _is_author_word(w):
                continue
            for n in range(_MIN_PATH_TOKEN, min(len(w), _MAX_PATH_TOKEN) + 1):
                if w[:n] in _PATH_TOKEN_SET:
                    return 2
    return 0


