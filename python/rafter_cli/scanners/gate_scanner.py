"""Static map of a codebase's security gates.

The functions whose names say they decide whether something is allowed,
ranked by likely security weight, plus "twin" groups of gates that implement
the same contract and the guard calls each twin makes. Line-based and
regex-only: no parsing, no network, no LLM.

Keep in step with node/src/scanners/gate-scanner.ts. Both runtimes must
produce identical output for the same tree (see CLI_SPEC.md).
"""
from __future__ import annotations

import os
import re

from .regex_scanner import DEFAULT_EXCLUDE, _filter_gitignored

A = re.ASCII

# ASCII whitespace, as \s means under re.ASCII; str.strip() with no argument
# also strips U+00A0, U+0085 and others, which the Node scanner must not.
WS = " \t\n\r\f\v"

# ── File selection ───────────────────────────────────────────────────

LANG_BY_EXT = {
    ".go": "go",
    ".py": "python",
    ".js": "javascript", ".jsx": "javascript", ".mjs": "javascript", ".cjs": "javascript",
    ".ts": "typescript", ".tsx": "typescript", ".mts": "typescript", ".cts": "typescript",
    ".java": "java",
    ".rb": "ruby",
}

# Directories that hold tests, docs, examples, vendored or generated code.
GATE_EXCLUDE_DIRS = set(DEFAULT_EXCLUDE) | {
    "test", "tests", "__tests__", "__mocks__", "spec", "specs", "testdata", "testutil",
    "testutils", "testing", "fixtures", "mocks", "e2e", "docs", "doc", "examples", "example",
    "samples", "sample", "third_party", "thirdparty", "site-packages", "generated",
    "benchmarks",
}

MAX_DEPTH = 40
MAX_FILE_BYTES = 1024 * 1024

TEST_FILE_RE = re.compile(r"(_test\.go|_test\.py|_test\.rb|_spec\.rb|\.(test|spec)\.[cm]?[jt]sx?|Tests?\.java|IT\.java)$", A)
PY_TEST_RE = re.compile(r"^(test_.*|conftest)\.py$", A)
GENERATED_NAME_RE = re.compile(r"(\.pb\.go|\.pb\.gw\.go|_generated\.go|\.gen\.go|_gen\.go|_pb2\.py|_pb2_grpc\.py|\.min\.js|\.bundle\.js|\.d\.ts|\.d\.mts|\.d\.cts)$|^zz_generated", A)
# "DO NOT EDIT" alone covers Go's "Code generated ... DO NOT EDIT" header; a `.*` between
# the two would make the search quadratic on a hostile first line.
GENERATED_MARK_RE = re.compile(r"DO NOT EDIT|@generated|autogenerated", A | re.I)


def _ext(name: str) -> str:
    return os.path.splitext(name)[1]


def _is_skipped_file(name: str) -> bool:
    return bool(TEST_FILE_RE.search(name) or PY_TEST_RE.search(name) or GENERATED_NAME_RE.search(name))


def _walk(directory: str, depth: int, out: list[str]) -> None:
    if depth >= MAX_DEPTH:
        return
    try:
        entries = sorted(os.scandir(directory), key=lambda e: e.name)
    except OSError:
        return
    for entry in entries:
        try:
            if entry.is_symlink():
                continue
            if entry.is_dir(follow_symlinks=False):
                if entry.name.startswith(".") or entry.name in GATE_EXCLUDE_DIRS:
                    continue
                _walk(entry.path, depth + 1, out)
            elif entry.is_file(follow_symlinks=False):
                if _ext(entry.name) not in LANG_BY_EXT or _is_skipped_file(entry.name):
                    continue
                out.append(entry.path)
        except OSError:
            continue


# ── Names ────────────────────────────────────────────────────────────

WORD_RE = re.compile(r"[A-Z]+(?=[A-Z][a-z])|[A-Z]?[a-z]+|[A-Z]+|\d+", A)
SPLIT_RE = re.compile(r"[^A-Za-z0-9]+", A)


def split_words(name: str) -> list[str]:
    """Split an identifier into lowercase words: camelCase, snake_case, kebab."""
    words: list[str] = []
    for part in SPLIT_RE.split(name):
        words.extend(w.lower() for w in WORD_RE.findall(part))
    return words


