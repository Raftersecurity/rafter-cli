# Regex calls dominate a Python scan, so each line first passes a substring
# test. Each test only checks for text that every definition pattern of its
# language requires, so it changes no result; the Node scanner skips it.


def _maybe_js(line: str) -> bool:
    if "function" in line or "class" in line or "exports." in line:
        return True
    if "(" in line or "=>" in line:
        if ":" in line:
            return True
        if "=" in line and ("const" in line or "let" in line or "var" in line):
            return True
    return ")" in line and line.rstrip(WS).endswith("{")


_MAYBE_DEF = {
    "go": lambda line: "func" in line or "type" in line,
    "python": lambda line: "def" in line or "class" in line,
    "ruby": lambda line: "def" in line or "class" in line,
    "java": lambda line: "(" in line or "class" in line or "interface" in line or "enum" in line or "record" in line,
    "javascript": _maybe_js,
    "typescript": _maybe_js,
}


def _arrow_ok(head: str, line: str) -> bool:
    """A `(` after `=` is a function only if an arrow follows on the line or the params continue."""
    if head != "(":
        return True
    return "=>" in line or line.endswith("(") or line.endswith(",")


def _match_def(lang: str, line: str):
    if lang == "go":
        m = GO_FUNC.match(line)
        if m:
            return m.group(2), ("method" if m.group(1) else "function")
        m = GO_TYPE.match(line)
        if m:
            return m.group(1), "type"
        return None
    if lang == "python":
        m = PY_DEF.match(line)
        if m:
            return m.group(3), ("method" if len(m.group(1)) > 0 else "function")
        m = PY_CLASS.match(line)
        if m:
            return m.group(1), "type"
        return None
    if lang in ("javascript", "typescript"):
        t = line.rstrip(WS)
        m = JS_FUNC.match(line)
        if m:
            return None if t.endswith(";") else (m.group(4), "function")
        m = JS_VAR.match(line)
        if m:
            return (m.group(3), "function") if _arrow_ok(m.group(6), t) else None
        m = JS_EXPORTS.match(line)
        if m:
            return (m.group(2), "function") if _arrow_ok(m.group(4), t) else None
        m = JS_PROTO.match(line)
        if m:
            return m.group(1), "method"
        m = JS_CLASS.match(line)
        if m:
            return m.group(4), "type"
        m = JS_PROP.match(line)
        if m:
            return (m.group(1), "method") if _arrow_ok(m.group(3), t) else None
        m = JS_METHOD.match(line)
        if m:
            return None if m.group(3) in KEYWORDS else (m.group(3), "method")
        return None
    if lang == "java":
        m = JAVA_CLASS.match(line)
        if m:
            return m.group(4), "type"
        if line.rstrip(WS).endswith(";"):
            return None
        m = JAVA_METHOD.match(line)
        if m:
            first_word = _JAVA_FIRST_RE.split(line.strip(WS))[0]
            if first_word in KEYWORDS or m.group(5) in KEYWORDS:
                return None
            return m.group(5), "method"
        return None
    if lang == "ruby":
        m = RB_DEF.match(line)
        if m:
            return _RB_SUFFIX_RE.sub("", m.group(2)), ("function" if m.group(1) else "method")
        m = RB_CLASS.match(line)
        if m:
            return m.group(1), "type"
        return None
    return None


# ── Bodies and guard calls ───────────────────────────────────────────

MAX_BODY_LINES = 400

_CLOSE_RE = re.compile(r"^\s*[)\]]", A)


def _indent_of(line: str) -> int:
    return len(line) - len(line.lstrip(WS))


def _strip_code(line: str, hash_comments: bool = False) -> str:
    """Remove string literals and line comments so braces inside them don't count.

    Each closed literal becomes `""`; an unclosed quote is kept and the scan
    goes on after it. One linear pass: a regex for this backtracks
    quadratically on a long line with an unclosed quote. Once a quote is
    unclosed, every later quote of that kind is too (its scan would fall into
    step with the first one), so each kind is scanned to the end at most once.
    """
    out = []
    unclosed = ""
    i, n = 0, len(line)
    while i < n:
        ch = line[i]
        if ch in "\"'`" and ch not in unclosed:
            j = i + 1
            while j < n and line[j] != ch:
                j += 2 if line[j] == "\\" else 1
            if j < n:
                out.append('""')
                i = j + 1
                continue
            unclosed += ch
        elif (ch == "/" and line[i + 1:i + 2] == "/") or (hash_comments and ch == "#"):
            break
        else:
            # Copy the run up to the next character that matters in one slice.
            j = i + 1
            while j < n and line[j] not in "\"'`/#":
                j += 1
            out.append(line[i:j])
            i = j
            continue
        out.append(ch)
        i += 1
    return "".join(out)


def _body_lines(lang: str, lines: list[str], code: list[str], start: int) -> list[int]:
    """Indexes of the lines in the body of the definition at ``start``."""
    end = min(len(lines), start + MAX_BODY_LINES)
    if lang in ("python", "ruby"):
        base = _indent_of(lines[start])
        body = [start]
        for i in range(start + 1, end):
            line = lines[i]
            if line.strip(WS) == "":
                continue
            if _indent_of(line) <= base:
                if lang == "ruby" and line.strip(WS).startswith("end"):
                    break
                if lang == "python" and _CLOSE_RE.match(line):
                    body.append(i)
                    continue
                break
            body.append(i)
        return body
    # Brace languages.
    depth = 0
    opened = False
    body = []
    for i in range(start, end):
        body.append(i)
        for ch in code[i]:
            if ch == "{":
                depth += 1
                opened = True
            elif ch == "}":
                depth -= 1
        if opened and depth <= 0:
            break
        if not opened and i - start >= 3:
            break
        if not opened and code[i].rstrip(WS).endswith(";"):
            break
    return body


# The lookbehind starts a match only at the head of an identifier, so a long
# run of identifier characters is scanned once instead of once per character.
CALL_RE = re.compile(r"(?<![\w$])([A-Za-z_$][\w$]*)\s*\(", A)

# Guard categories, matched against the called name lowercased with
# underscores removed, with the weight a missing one carries when ranking
# twin groups. Order is output order.
GUARD_CATEGORIES = [
    ("escape", re.compile(r"escape|quote|sanitiz|sanitis|purify|striptags|encodeuri|htmlspecialchars", A), 3),
    ("normalize", re.compile(r"clean|normaliz|normalis|normpath|realpath|abspath|evalsymlinks|canonical", A), 3),
    ("containment", re.compile(r"^(rel|relpath|relative)$|hasprefix|startswith|hassuffix|endswith|islink|lstat|within|containspath|isrelativeto", A), 3),
    ("constant_time", re.compile(r"constanttimecompare|comparedigest|timingsafeequal|securecompare|constanttimeeq|safeequal|^equal$", A), 3),
    ("expiry", re.compile(r"expir|revok|notbefore|notafter", A), 3),
    ("authz", re.compile(r"authoriz|authoris|permi|allow|deny|forbid|access", A), 2),
    ("authn", re.compile(r"authent|login|password", A), 2),
    ("limit", re.compile(r"limit|max|bound|truncat|throttle", A), 2),
    ("verify", re.compile(r"verif", A), 1),
    ("validate", re.compile(r"valid", A), 1),
    ("check", re.compile(r"check", A), 1),
]
CATEGORY_WEIGHT = {c: w for c, _, w in GUARD_CATEGORIES}

# Calls ending in these words construct a value; they are not guards.
VALUE_WORDS = {"result", "results", "error", "errors", "exception", "options", "config", "info", "type"}

CALL_KEYWORDS = KEYWORDS | {"require", "import"}

_HMAC_BEFORE_RE = re.compile(r"(hmac|subtle)\.$", A)


def _guard_calls(code: list[str], body: list[int], self_name: str) -> dict[str, list[str]]:
    found: dict[str, set[str]] = {}
    # Drop the definition's own name from its first line.
    text = "\n".join(code[li].replace(self_name, "", 1) if i == 0 else code[li] for i, li in enumerate(body))
    self_low = self_name.lower().replace("_", "")
    for m in CALL_RE.finditer(text):
        ident = m.group(1)
        low = ident.lower().replace("_", "")
        if low == self_low or ident in CALL_KEYWORDS:
            continue
        if low.startswith("un"):
            continue  # unquote, unescape: the reverse of a guard
        id_words = split_words(ident)
        if id_words and id_words[-1] in VALUE_WORDS:
            continue
        for cat, rx, _ in GUARD_CATEGORIES:
            if cat == "constant_time" and low == "equal":
                before = text[max(0, m.start() - 8):m.start()]
                if not _HMAC_BEFORE_RE.search(before):
                    continue
            if rx.search(low):
                found.setdefault(cat, set()).add(ident)
                break
    return {cat: sorted(found[cat]) for cat, _, _ in GUARD_CATEGORIES if cat in found}


# ── Twins ────────────────────────────────────────────────────────────

# Variant markers: async/sync pairs, implementations, versions. Dropped anywhere.
VARIANT_WORDS = {"async", "sync", "impl", "internal", "inner", "v"}

# Backend-ish words: dropped anywhere when what remains still names a contract.
BACKEND_WORDS = {
    "legacy", "old", "new", "default", "sql", "sqlite", "postgres", "pg", "mysql", "mongo",
    "redis", "ldap", "local", "memory", "mem", "db", "file", "fs", "http", "grpc", "rest", "ws",
    "s3", "gcs", "azure", "remote",
}

SECURITY_WORDS = set(VERBS) | IS_WORDS | HAS_WORDS | set(ROLE_WORDS) | {"is", "has"}


def _twin_key(name: str, rel: str) -> str:
    """The contract a gate implements, from its name.

    `ldapAuthenticate` in ldap.go, `authenticate_async` and `AuthenticateV2`
    all key to "authenticate". Words naming the file or its directory are
    dropped from either end of the name. A key reduced to one weak verb
    ("check") is too generic to pair on, so the unstripped name is used.
    """
    base = [w for w in split_words(name) if not w.isdigit() and w not in VARIANT_WORDS]
    if len(base) > 1 and base[0] == "do":
        base = base[1:]
    if not base:
        return ""
    segs = rel.split("/")
    ctx = set(split_words(_EXT_RE.sub("", segs[-1], count=1)))
    if len(segs) > 1:
        ctx |= set(split_words(segs[-2]))

    def strippable(w: str) -> bool:
        return w in ctx and w not in SECURITY_WORDS

    kept = [w for w in base if w not in BACKEND_WORDS]
    if len(kept) > 1 and strippable(kept[0]):
        kept = kept[1:]
    if len(kept) > 1 and strippable(kept[-1]):
        kept = kept[:-1]
    strong_bare = len(kept) == 1 and VERBS.get(kept[0], 0) >= 3
    if not kept or (len(kept) == 1 and not strong_bare and len(base) > 1):
        kept = base
    return "".join(kept)


MAX_TWIN_GROUP = 8


def _build_twins(gates: list[dict]) -> list[dict]:
    candidates = [g for g in gates if g["kind"] != "type"]
    keys = [_twin_key(g["name"], g["file"]) for g in candidates]
    key_set = set(keys)
    groups: dict[str, list[dict]] = {}
    for g, k in zip(candidates, keys):
        # aauthenticate / acheck_password: an a-prefixed async twin.
        if len(k) > 2 and k.startswith("a") and k[1:] in key_set:
            k = k[1:]
        # A bare weak verb (`Check`, `Validate` on unrelated types) names no shared contract.
        if not k or VERBS.get(k, 2) < 2:
            continue
        groups.setdefault(k, []).append(g)
    scored = []
    for key, members in groups.items():
        if len(members) < 2 or len(members) > MAX_TWIN_GROUP:
            continue
        present = {c for m in members for c in m["guards"]}
        cats = [c for c, _, _ in GUARD_CATEGORIES if c in present]
        missing = [c for c in cats if any(c not in m["guards"] for m in members)]
        t = {
            "key": key,
            "flagged": len(missing) > 0,
            "missing": missing,
            "members": [
                {
                    "file": m["file"],
                    "line": m["line"],
                    "name": m["name"],
                    "guards": m["guards"],
                    "lacks": [c for c in missing if c not in m["guards"]],
                }
                for m in members
            ],
        }
        severity = max([0] + [CATEGORY_WEIGHT[c] for c in missing])
        scored.append((t, severity, max(m["score"] for m in members)))
    scored.sort(key=lambda s: (-s[1], -s[2], -len(s[0]["missing"]), s[0]["key"]))
    return [s[0] for s in scored]


# ── Entry point ──────────────────────────────────────────────────────

MAX_SIGNATURE = 90
# Longer lines are minified or data, not definitions; skipping them also
# bounds regex backtracking.
MAX_DEF_LINE = 400
# Body lines read per file, summed over its gates. Real files stay far below;
# a file of thousands of unclosed definitions is data, and is skipped like an
# oversize file rather than read 400 lines per definition.
MAX_BODY_WORK = 100_000


def _scan_file(abs_path: str, rel: str, lang: str, out: list[dict]) -> bool:
    try:
        if os.path.getsize(abs_path) > MAX_FILE_BYTES:
            return False
        with open(abs_path, encoding="utf-8", errors="replace", newline="") as f:
            content = f.read()
    except OSError:
        return False
    if content.startswith("\ufeff"):
        content = content[1:]
    lines = [line[:-1] if line.endswith("\r") else line for line in content.split("\n")]
    if GENERATED_MARK_RE.search("\n".join(lines[:5])):
        return False
    # Each line stripped once; bodies overlap, so per-gate stripping is quadratic.
    hash_comments = lang in ("python", "ruby")
    code = [_strip_code(line, hash_comments) for line in lines]
    pw = _path_weight(rel)
    maybe_def = _MAYBE_DEF[lang]
    body_work = 0
    found = []
    for i, line in enumerate(lines):
        if len(line) > MAX_DEF_LINE or not maybe_def(line):
            continue
        d = _match_def(lang, line)
        if not d:
            continue
        name, kind = d
        words = split_words(name)
        nw = _name_weight(words, kind)
        if nw == 0:
            continue
        guards: dict[str, list[str]] = {}
        if kind != "type":
            body = _body_lines(lang, lines, code, i)
            body_work += len(body)
            if body_work > MAX_BODY_WORK:
                return False
            guards = _guard_calls(code, body, name)
        sig = line.strip(WS)
        if len(sig) > MAX_SIGNATURE:
            sig = sig[:MAX_SIGNATURE - 3] + "..."
        found.append({
            "file": rel,
            "line": i + 1,
            "name": name,
            "kind": kind,
            "language": lang,
            "score": nw + _token_weight(words) + pw,
            "signature": sig,
            "guards": guards,
        })
    out.extend(found)
    return True


def map_gates(target: str, *, limit: int, respect_gitignore: bool = True) -> dict:
    """Map the security gates under ``target`` (a directory or a single file)."""
    root = os.path.abspath(target)
    if os.path.isdir(root):
        files: list[str] = []
        _walk(root, 0, files)
        if respect_gitignore:
            files = _filter_gitignored(files, root)
        base = root
    else:
        files = [root] if _ext(root) in LANG_BY_EXT else []
        base = os.path.dirname(root)
    gates: list[dict] = []
    scanned = 0
    for abs_path in files:
        rel = os.path.relpath(abs_path, base).replace(os.sep, "/")
        if _scan_file(abs_path, rel, LANG_BY_EXT[_ext(abs_path)], gates):
            scanned += 1
    gates.sort(key=lambda g: (-g["score"], g["file"], g["line"]))
    twins = _build_twins(gates)
    shown = [{k: v for k, v in g.items() if k != "guards"} for g in gates[:limit]]
    return {
        "stats": {
            "files_scanned": scanned,
            "gates_found": len(gates),
            "gates_shown": len(shown),
            "twin_groups": len(twins),
            "flagged_groups": sum(1 for t in twins if t["flagged"]),
        },
        "gates": shown,
        "twins": twins,
    }


# ── Text ─────────────────────────────────────────────────────────────

MAX_FLAGGED_TEXT = 10
MAX_MEMBERS_TEXT = 5
MAX_OTHER_TEXT = 8


def _guard_summary(guards: dict[str, list[str]]) -> str:
    parts = [f"{c}: {', '.join(ids[:2])}" for c, ids in guards.items()]
    return "; ".join(parts) if parts else "no guard calls"


def format_gate_map(gate_map: dict) -> str:
    s = gate_map["stats"]
    out = [
        f"rafter gates: {s['files_scanned']} files scanned, {s['gates_found']} gates found, "
        f"{s['twin_groups']} twin groups, {s['flagged_groups']} flagged",
        "",
        f"Gates (top {s['gates_shown']} of {s['gates_found']}, ranked by likely security weight; score file:line signature):",
    ]
    for g in gate_map["gates"]:
        out.append(f"  {g['score']}  {g['file']}:{g['line']}  {g['signature']}")
    if s["gates_shown"] < s["gates_found"]:
        out.append(f"  ... {s['gates_found'] - s['gates_shown']} more (--limit N or --json)")

    flagged = [t for t in gate_map["twins"] if t["flagged"]]
    other = [t for t in gate_map["twins"] if not t["flagged"]]
    out.append("")
    out.append("Flagged twin groups (same contract; a member lacks a guard its twins call):")
    if not flagged:
        out.append("  none")
    for t in flagged[:MAX_FLAGGED_TEXT]:
        out.append(f"  {t['key']} ({len(t['members'])}): missing {', '.join(t['missing'])}")
        for m in t["members"][:MAX_MEMBERS_TEXT]:
            lacks = f"  lacks: {', '.join(m['lacks'])}" if m["lacks"] else ""
            out.append(f"    {m['file']}:{m['line']}  {m['name']}  [{_guard_summary(m['guards'])}]{lacks}")
        if len(t["members"]) > MAX_MEMBERS_TEXT:
            out.append(f"    ... {len(t['members']) - MAX_MEMBERS_TEXT} more members (--json)")
    if len(flagged) > MAX_FLAGGED_TEXT:
        out.append(f"  ... {len(flagged) - MAX_FLAGGED_TEXT} more flagged groups (--json)")

    out.append("")
    out.append("Other twin groups:")
    if not other:
        out.append("  none")
    for t in other[:MAX_OTHER_TEXT]:
        ms = ", ".join(f"{m['file']}:{m['line']}" for m in t["members"][:4])
        more = f", +{len(t['members']) - 4}" if len(t["members"]) > 4 else ""
        out.append(f"  {t['key']} ({len(t['members'])}): {ms}{more}")
    if len(other) > MAX_OTHER_TEXT:
        out.append(f"  ... {len(other) - MAX_OTHER_TEXT} more (--json)")
    out.append("")
    out.append("Next: read each gate, state its contract, and name an input it should reject but accepts (rafter-code-review, section 0).")
    return "\n".join(out) + "\n"
